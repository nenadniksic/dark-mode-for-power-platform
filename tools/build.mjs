#!/usr/bin/env node
/*
 * Build: bundles theme/*.css into src/content/generated/theme-css.js (so the
 * content script can inject CSS synchronously at document_start with no
 * fetch), validates the manifest, and optionally emits a standalone bundle
 * (dist/standalone/capd-standalone.js) that runs the whole engine without
 * extension APIs — used for Playwright-driven visual checks.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.join(here, '..');
const rel = (p) => path.relative(rootDir, p);

/* 1. theme CSS bundle */
const themeDir = path.join(rootDir, 'theme');
const parts = {};
for (const file of fs.readdirSync(themeDir).filter((f) => f.endsWith('.css')).sort()) {
  const key = file.replace(/\.css$/, '');
  const css = fs.readFileSync(path.join(themeDir, file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')   // strip comments
    .replace(/\s+/g, ' ')               // collapse whitespace
    .replace(/\s*([{};:,>])\s*/g, '$1')  // tighten punctuation
    .trim()
    // Inside the runtime @scope (:root) wrapper only the scoping root itself
    // matches :scope; a leading `html` would have to be a descendant of html.
    .replace(/html\[data-capd="dark"\]/g, ':scope[data-capd="dark"]');
  parts[key] = css;
}
const genDir = path.join(rootDir, 'src', 'content', 'generated');
fs.mkdirSync(genDir, { recursive: true });
const themeOut = `/* Generated by tools/build.mjs from theme/*.css — do not edit by hand. */
(function (root) {
  'use strict';
  const CAPD = (root.CAPD = root.CAPD || {});
  CAPD.themeCSS = ${JSON.stringify(parts, null, 1)};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(genDir, 'theme-css.js'), themeOut);
console.log('theme bundle:', Object.entries(parts).map(([k, v]) => `${k} ${v.length}B`).join(', '));

/* 2. manifest sanity */
const manifest = JSON.parse(fs.readFileSync(path.join(rootDir, 'manifest.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(rootDir, 'package.json'), 'utf8'));
if (manifest.version !== pkg.version) throw new Error(`manifest version ${manifest.version} != package version ${pkg.version}`);
const referenced = new Set();
for (const cs of manifest.content_scripts) for (const f of cs.js) referenced.add(f);
referenced.add(manifest.background.service_worker);
referenced.add(manifest.action.default_popup);
referenced.add(manifest.options_ui.page);
for (const v of Object.values(manifest.icons)) referenced.add(v);
const missing = [...referenced].filter((f) => !fs.existsSync(path.join(rootDir, f)));
if (missing.length) { console.warn('manifest references missing files:\n  ' + missing.join('\n  ')); if (!process.argv.includes('--allow-missing')) process.exitCode = 1; }
else console.log('manifest ok:', referenced.size, 'files referenced');

/* 3. standalone bundle for browser-driven testing */
if (process.argv.includes('--standalone')) {
  const order = [
    'src/main-world/cssom-hooks.js',
    'src/shared/settings.js',
    'src/shared/timezones.js',
    'src/shared/schedule.js',
    'src/content/00-namespace.js',
    'src/content/generated/fluent-tokens.js',
    'src/content/generated/theme-css.js',
    'src/content/10-color.js',
    'src/content/20-css-rewriter.js',
    'src/content/30-style-manager.js',
    'src/content/40-inline.js',
    'src/content/50-dom-observer.js',
    'src/content/60-static-theme.js',
    'src/content/70-audit.js',
    'src/content/90-main.js',
  ];
  const shim = `/* standalone shim: no extension APIs; settings come from window.__capdSettings */\n(function(){ if (typeof chrome === 'undefined') { globalThis.chrome = undefined; } })();\n`;
  const bundle = shim + order.map((f) => `\n/* ---- ${f} ---- */\n` + fs.readFileSync(path.join(rootDir, f), 'utf8')).join('\n');
  const outDir = path.join(rootDir, 'dist', 'standalone');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'capd-standalone.js'), bundle);
  console.log('standalone bundle:', rel(path.join(outDir, 'capd-standalone.js')), `${bundle.length}B`);
}
